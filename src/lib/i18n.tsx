interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key: string) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>('en');

  useEffect(() => {
    if (typeof window !== 'undefined') {
      const urlParams = new URLSearchParams(window.location.search);
      const urlLang = urlParams.get('lang') as Language;
      if (urlLang && translations[urlLang]) {
        setLanguageState(urlLang);
        localStorage.setItem('aicte_lang', urlLang);
        return;
      }
      const saved = localStorage.getItem('aicte_lang') as Language;
      if (saved && translations[saved]) {
        setLanguageState(saved);
      }
    }

    const handleLangChange = () => {
      const current = localStorage.getItem('aicte_lang') as Language;
      if (current && translations[current]) {
        setLanguageState(current);
      }
    };

    window.addEventListener('aicte_language_changed', handleLangChange);
    return () => window.removeEventListener('aicte_language_changed', handleLangChange);
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    if (typeof window !== 'undefined') {
      localStorage.setItem('aicte_lang', lang);
      window.dispatchEvent(new Event('aicte_language_changed'));
    }
  };

  const t = (key: string): string => {
    const langDict = translations[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    return translations['en'][key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useTranslation = () => useContext(LanguageContext);
